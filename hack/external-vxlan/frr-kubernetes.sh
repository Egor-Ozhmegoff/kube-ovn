#!/usr/bin/env bash
set -euo pipefail
# Provisions host FRR control-plane interfaces ONLY on a fresh disposable fixture.
# Clones the separate test lab's FRR config, never production FRR configuration.
: "${KUBECONFIG:?Set the dedicated test kubeconfig}"
: "${EXTERNAL_VXLAN_GATEWAY_NODE:?Set the first kind node container}"
: "${EXTERNAL_VXLAN_SECOND_NODE:?Set the second kind node container}"
: "${FRR_TEST_CONFIGS:?Set the frr-lab.sh artifacts directory}"
: "${EXTERNAL_VXLAN_IMAGE:?Set the pinned OVN lab image}"
dir=$(cd "$(dirname "$0")" && pwd)
prefix=${EXTERNAL_VXLAN_LAB:?Set the dedicated kind cluster/lab prefix}
fabric=${EXTERNAL_VXLAN_FABRIC_PREFIX:-10.110.193}
cluster=${EXTERNAL_VXLAN_CLUSTER_PREFIX:-10.110.194}
out=${FRR_KUBERNETES_ARTIFACTS:-/tmp/$prefix-frr}
image=${FRR_TEST_IMAGE:-quay.io/frrouting/frr@sha256:eae3340ca578bb588d92ab3d1e77deb806f80d1da2bc0053cb1dfcfef2aa236f}
kc() { kubectl --cache-dir "${EXTERNAL_VXLAN_KUBECTL_CACHE:-/tmp/ko-evx-kubectl}" "$@"; }
for node in "$EXTERNAL_VXLAN_GATEWAY_NODE" "$EXTERNAL_VXLAN_SECOND_NODE"; do
  [[ $(docker inspect --format '{{index .Config.Labels "io.x-k8s.kind.cluster"}}' "$node") == "$prefix" ]] || { echo "Refusing non-test kind node $node" >&2; exit 1; }
done
index=0
for node in "$EXTERNAL_VXLAN_GATEWAY_NODE" "$EXTERNAL_VXLAN_SECOND_NODE"; do
  index=$((index+1))
  mac=$(printf '02:ee:%02x:00:00:00' "$((index+10))")
  docker exec -i "$node" bash -s -- "$fabric.1$index" "$mac" <<'HOST_SETUP'
set -euo pipefail
for tenant in 220 230; do ip link add "vrf$tenant" type vrf table "$tenant"; ip link set "vrf$tenant" up; done
for pair in 220:220 230:230 504221:220 504231:230 504223:220 504232:230; do
  vni=${pair%:*}; tenant=${pair#*:}
  ip link add "evb$vni" type bridge
  ip link set "evb$vni" master "vrf$tenant" addrgenmode none mtu 9000 up
  if [[ $vni == "$tenant" ]]; then ip link set "evb$vni" address "$2"; fi
  ip link add "evx$vni" type vxlan id "$vni" local "$1" dstport 60000 nolearning
  ip link set "evx$vni" master "evb$vni" addrgenmode none multicast off arp off up
  ip link add "eva$vni" type dummy
  ip link set "eva$vni" master "evb$vni" addrgenmode none mtu 9000 up
  for iface in "evb$vni" "evx$vni" "eva$vni"; do sysctl -qw "net.ipv6.conf.$iface.disable_ipv6=1"; done
done
HOST_SETUP
  pod=$(kc -n kube-system get pods -l app=ovs --field-selector "spec.nodeName=$node" -o 'jsonpath={.items[0].metadata.name}')
  suffix=""
  [[ $index != 2 ]] || suffix=-b
  kc -n kube-system exec "$pod" -- ovs-vsctl set Open_vSwitch . "external_ids:ovn-evpn-local-ip=$fabric.1$index" external_ids:ovn-evpn-vxlan-ports=4789 "external_ids:dynamic-routing-port-mapping=lr-transit220$suffix=evb220,lr-transit230$suffix=evb230"
done
docker exec -e "EXTERNAL_VXLAN_FABRIC_PREFIX=$fabric" "$prefix-peer" bash /lab/frr-host.sh peer
mkdir -p "$out"
for name in hv1 hv2 peer; do
  mkdir -p "$out/$name"
  # The source files are generated by this repository's isolated test lab.
  sed -e '/neighbor 10\.110\.191\.1[34] /d' -e "s/10\.110\.191/$fabric/g" "$FRR_TEST_CONFIGS/$name/frr.conf" > "$out/$name/frr.conf"
  touch "$out/$name/vtysh.conf"
  node=$EXTERNAL_VXLAN_GATEWAY_NODE
  [[ $name != hv2 ]] || node=$EXTERNAL_VXLAN_SECOND_NODE
  [[ $name != peer ]] || node=$prefix-peer
  docker run -d --privileged --name "$prefix-frr-$name" --label "kube-ovn.external-vxlan-lab=$prefix" --network "container:$node" \
    --mount "type=bind,source=$out/$name,target=/etc/frr" --entrypoint /bin/sh "$image" -c \
    'set -e; /usr/lib/frr/mgmtd -d; /usr/lib/frr/zebra -d -f /dev/null; /usr/lib/frr/bgpd -d -f /dev/null; vtysh -b; exec sleep infinity'
done
docker network create --subnet "$cluster.0/24" --label "kube-ovn.external-vxlan-lab=$prefix" "$prefix-cluster"
EXTERNAL_VXLAN_CLUSTER_PREFIX=$cluster bash "$dir/frr-reference-peer.sh"
echo 'Host FRR provisioned. Run kubernetes.sh configure and secondary.sh configure, then wait for BGP/OVN convergence and run their checks.'
